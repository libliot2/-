REPORT = """# 文献比较

## 使用边界与 V2 人口口径

本比较只使用 `docs/literature_context/` 中的冻结证据包。证据索引中的 A/B/C 原按较窄人口定义分级，未按 V2 的广义口径重新评级，不能直接当作对 V2 整体的人口贴近度。DP001/DP002 只能支持可分离的相近个案；其中 DP002 的一个跨境个案在 V2 下新具直接相关性，但不足以代表跨境学生。当前参与者主张始终来自问卷表和编号访谈，文献只作比较与解释。

## 1. 教育制度断裂与规则学习

**当前资料。** 在 35 份问卷中，插班初期报告“比较/非常困难”的项目包括小组项目 23/34、繁体字 23/32、粤语课堂 22/34、混合评价 22/35 和口头汇报 18/33；后期 32/34 认同已经理解评价方式（`survey_item_statistics.csv`）。这些不是等价前后测。P01 释义显示参与者通过英语口语任务及评分反馈识别“敢说”的评价逻辑（P01，L0010）；P02 对显性纪律与考试要求记忆较清楚，却难以重建完整规则学习过程（P02，L0064–L0084）；一个受限链接个案则出现较低问卷困难回答与多项具体摩擦叙述并存，公开文本不披露其代号、背景组合或行号。

**既有证据。** DP001/DP002 的早期质性材料只提示英语、年级位置、教师、同伴与家庭支持进入具体经历，不能估计比例；DP002 内含的跨境个案须与迁居个案分开理解。B 级研究强调年级位置可能改变学业比较，但不能证明降级或早入学带来收益（D1-004）；其他 B 级学业结果并不一致（DP011、D1-012、D1-018）。C 级制度研究显示香港课堂可能同时包含学生中心、考试取向、形成性与总结性评价（D1-008、D1-009、D1-017），不能作为本样本亲历。

**关系。** 当前结果**支持并扩展**“制度接口需拆开分析”的观点：困难落在语言、任务、评价、分组和支持时机，而非单一能力缺陷。受限个案还提示原工具对扩大后人口范围的适配风险。初期困难与后期规则理解的探索性关联未通过 FDR 门槛（A2：q=0.0790），不能把困难写成促进掌握的过程。

## 2. 同伴边界、归属与关系深度

**当前资料。** 插班初期，本地知识障碍经常/非常经常为 14/35，因担忧而减少参与为 11/33；后期对复合陈述“至少一位可以信任并谈心的同学”给出正向回答为 35/35，成员感为 30/33（`survey_item_statistics.csv`）。初期边界与后期归属的排序关联为 A1：n=30，ρ=-0.499，BH-FDR q=0.0291；它只描述 V2 样本的回顾性共变，不识别方向或变化。P01 的问卷正向回答与访谈“没有交心朋友”构成同题直接分歧（P01，L0021）；问卷不能把信任和谈心拆成各自比例。P02 的广泛友好与少数密友，以及受限案例的核心友谊与稳定群体自评，只用于区分成员感、求助、亲密和群体门槛。

**既有证据。** B 级香港研究提示口音和语言地位可参与边界协商，但熟练度不等于被承认（DP005）；广义移民样本的归属或学校环境并不总是较低（DP009、D1-016），另有研究同时报告福祉风险与支持相关（DP012、DP015）。这些研究的人口定义、年代和结局不同，不能合并为单一结论。边界工作理论（TM008，C）只提供分析工具。

**关系。** 当前资料**支持并细化**“归属与排斥不是同一指标”，并以地方知识、任务分组、功能性关系和亲密门槛加以扩展。A1 与三个个案均不允许写成“边界造成低归属”：回忆时点、题意、学校/班级环境、个人交往选择和未测资源都可能解释关联。

## 3. 支持的来源、功能、时机与可见性

**当前资料。** 香港本地同学（23/35）和具有内地经历的同学（19/35）是最常被选为主要帮助的资源。支持状态并不等同于充分：情绪/反排斥支持的未满足需求为 5/30，英文支持为 4/33（`support_gap_analysis.csv`）。P01 释义呈现同背景同伴早期提供翻译、制度与关系入口，后期同一安全圈与跨群体拓展动力下降并存（P01，L0016–L0018）；P02 呈现即时答疑、少数密友、同伴代沟通及不过度显眼的支持偏好（P02，L0041–L0044、L0207–L0212、L0239–L0248）；第三条支持路径只在受限证据层保留，以避免跨版本间接识别。

**既有证据。** DP003（B）提示内地旧友、本地同学及具有内地经历的香港同学可能承担不同功能；D1-001、DP012、DP015 等 B 级研究主要提供横截面相关，不能说明支持导致归属。教育局资料 DP020（B，政策背景）只能证明项目存在，不能证明参与者使用或项目效果。

**关系。** 当前结果**支持并扩展**关系功能分化：谁提供、何时提供、是否创造参与入口、家庭能否购买额外资源以及支持是否过度突出，都可能影响主观意义。支持项目数与归属的 A3 未通过 FDR（q=0.1218）；三个个案也不能验证支持效果或推荐单一方案。

## 4. 身份协商与文化中介

**当前资料。** 调整表达获 31/31 正向回答，解释两地差异为 29/34；解释者疲惫为 9/32，双重边缘感分布更分散（`survey_item_statistics.csv`）。解释差异与疲惫的 A4 为 n=32、ρ=-0.430、q=0.0353，但两个单项不是量表，负向关联不能解释为中介行为具有保护作用。访谈证据不一致：P01 没有足够的主动中介事件；P02 最清楚的是朋友替参与者沟通，不能倒转角色；一个受限个案出现有限的一对一差异解释事件，但没有稳定中介角色或负担证据。

**既有证据。** 香港 B 级研究支持多重身份、跨群体关系和能动性可以并存（DP003、DP004、DP005、D1-015），但网络位置不证明中介行为。家庭语言中介元分析与概念综述（D3-017、TM011，C）强调角色形式、评价和负担依情境而异，不能直接移植为香港学校事实。

**关系。** 当前问卷与多维、情境化身份框架**相容**；受限个案为具体解释行动提供有限**扩展**，P01/P02 的沉默或角色错位则**复杂化**把问卷单项、网络位置和稳定“文化桥梁”类型等同的做法。A4 需要在预先界定、中介事件可测且样本更大的研究中复核。

## 5. 数字平台作为关系基础设施

**当前资料。** 两个回顾时点的边际选择人数显示：微信/朋友圈为 32/35 与 27/35，WhatsApp 为 0/35 与 26/35；Instagram 后期为 23/35，插班前小格不公开（`platform_transition_analysis.csv`）。这不是个体配对的保留或替代率。Q6.2 后期微博列缺失，不能比较。三个案例的问卷都提供不同程度的平台—关系分工回答，但访谈没有平台、受众与功能同时出现的充分事件。

**既有证据。** 文献库没有覆盖 V2 全部异质路径的直接数字研究。DP003（B）只有零散平台片段；香港高校生、成人或其他移民社会的 polymedia/media-repertoire 研究（D2-003、D2-006、TM012、TM013，C）只提供媒体组合机制，不能证明本样本的平台效果。

**关系。** 问卷**支持**多个平台并存及按关系分工的描述，访谈则对机制保持 **silence**。平台分工与同伴网络的 A5 无关联信号（q=0.9886）。现有资料不能声称平台促进归属、新平台替代旧平台，或由平台选择推断文化/政治身份。

## 6. 当前研究的增量与限制

当前研究的增量是：

1. 将 35 份问卷与三个唯一链接访谈放入同一证据链，同时保留 V1 的 24/35 结果作口径敏感性；
2. 显示较低年级、跨境/居住和就学年限差异会改变目标人口异质性及工具适配，而非构成自动排除；
3. 把语言、地方知识、分组、评价、支持时机和家庭资源拆为可追溯接口；
4. 显示相似问卷回答可来自不同关系路径，也显示较低困难回答可与多项具体摩擦叙述并存；
5. 将文化中介具体事件与平台访谈沉默分开处理。

限制包括资格口径在资料收集后扩展、非概率小样本、回顾性自报、三个链接案例选择理由未记录、一份整理式记录和两份未核音机器转写，以及冻结文献分级依据旧人口定义。因而，本研究只能说当前资料**支持、扩展、复杂化或不同于**某些既有发现，不能评估香港所有内地—香港插班学生、跨境学生或学校政策效果。
"""


