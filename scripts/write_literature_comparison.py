REPORT = """# 文献比较

## 使用边界

本比较只使用 `docs/literature_context/` 中的冻结证据包。A/B/C 表示研究对象与本项目严格人口的贴近程度，不代表方法质量。当前样本主张来自问卷表和编号访谈；文献只用于比较与解释。

## 1. 教育制度断裂与规则学习

**当前资料。** 在 24 份合资格问卷中，插班初期报告“比较/非常困难”较多的项目包括繁体字、小组项目、综合考评、粤语课堂和口头汇报；到香港校内后期，多数有效回答者同意已理解作业、评价和课堂参与规则（`survey_item_statistics.csv`）。这些题不是等价前后测。P01 具体描述了通过英语口语任务和成绩反馈识别“敢说”的评价逻辑（P01，L0010）；P02 只较清楚记得学校和考试管理严格，无法重建规则掌握过程（P02，L0066–L0077）。

**既有证据。** 两项 A 级早期质性材料只提示英语、年级位置、教师、同伴与家庭支持进入具体经历（DP001、DP002），不能估计比例。B 级研究强调年级位置会改变学业比较，但不能证明降级带来收益（D1-004）；其他 B 级学业结果并不一致（DP011、D1-012、D1-018）。C 级制度研究说明香港课堂中的学生中心、考试取向、形成性与总结性评价可能混合存在（D1-008、D1-009、D1-017），不能作为插班生亲历。

**关系。** 当前结果**支持并扩展**“制度接口需拆开分析”的观点：困难集中在具体语言、任务与评价形式，而不是单一能力缺陷。P01 提供了既有严格人口文献较少呈现的微观规则学习过程；P02 则**复杂化**了问卷中的后期掌握回答，显示多年后回忆可能只保留“严格”印象。当前资料不支持“内地应试—香港全人”的二元比较。

## 2. 同伴边界、归属与关系深度

**当前资料。** 插班初期，本地知识障碍经常/非常经常为 9/24，因担忧而减少参与为 9/23；后期可信同学为 24/24 同意，成员感为 21/24 同意（`survey_item_statistics.csv`）。这说明本样本中初期边界经验与后期较高归属回答可以并存。两个链接案例进一步区分网络构成、成员感、可求助性和深度亲密：P01 的问卷可信任同学与访谈“没有交心朋友”形成分歧（P01，L0021）；P02 区分多数同学友好与一两位密友（P02，L0093）。

**既有证据。** B 级香港研究提示口音和语言地位可参与边界协商，但熟练度不等于被承认（DP005）；广义移民样本的归属或学校环境并不总是较低（DP009、D1-016），其他研究同时报告福祉风险与支持相关（DP012、DP015）。这些研究的人口定义、年代和结局不同，不能合并为单一结论。边界工作理论（TM008，C）只提供分析工具。

**关系。** 当前资料**支持并细化**“归属与排斥不是同一指标”的文献判断，并**扩展**了地方知识、小组任务和亲密关系门槛的事件层信息。它也提供负例：较少参与不一定等于被排斥，较高成员感也不能否定具体距离感。由于问卷为回顾性横截面资料，初期边界与后期归属的探索性相关不能证明方向。

## 3. 同伴支持的功能与时序

**当前资料。** 问卷中，香港本地同学和具有内地经历的同学都是常被选为主要帮助的资源；Q5.5 同时区分“已获得但帮助有限”与“没有获得但希望获得”（`support_gap_analysis.csv`）。P01 描述同背景同伴早期提供翻译、制度/地方信息和关系入口，后来成为相对独立安全圈（P01，L0016、L0018）；P02 的路径则是同伴主动答疑、拉入活动、少数密友及代为沟通（P02，L0038–L0043、L0167、L0212）。

**既有证据。** DP003（B）提示内地旧友、本地同学及具有内地经历的香港同学可能承担不同支持功能；D1-001、DP012、DP015 等 B 级研究主要提供横截面相关，不能说明支持导致归属。教育局资料 DP020（B，政策背景）只能证明支援项目存在，不能证明使用或效果。

**关系。** 当前结果**支持**关系功能分化，并通过 P01 的安全圈时序权衡和 P02 的非侵入式支持偏好**扩展**了过程解释。两案差异也**复杂化**“同伴支持越多越好”的简单命题：支持的提供者、强度、时点和参与者偏好均可能改变其含义。五项探索性关联经 BH-FDR 后均无 q<0.05，因此不把支持与归属写成统计成立或因果机制。

## 4. 身份协商与文化中介

**当前资料。** 问卷中，调整表达、解释两地差异和不必二选一的同意比例较高；解释者疲惫与双重边缘感呈不同分布（`survey_item_statistics.csv`）。然而，两份合资格访谈都没有参与者本人实施跨背景解释、翻译或连接的充分事件。P02 是朋友替其沟通（P02，L0212），不能转写成 P02 的文化中介。

**既有证据。** 香港 B 级研究支持多重身份、跨群体关系和能动性可以并存（DP003、DP004、DP005、D1-015），但网络位置不证明中介行为。家庭语言中介元分析与概念综述（D3-017、TM011，C）强调角色形式、评价和负担依情境而异，不能直接移植为香港学校事实。

**关系。** 当前问卷结果与文献的多维身份框架**相容**，但访谈沉默使文化中介机制成为**silence**，不是验证。当前资料**复杂化**把解释行为、网络桥接、认可和负担合成稳定“文化桥梁”类型的做法。

## 5. 数字平台作为关系基础设施

**当前资料。** 两个回顾时点的边际选择人数显示 WhatsApp 与 Instagram 在后期较多，香港校内后期仍有 18/24 选择微信；后期微信主要联系内地旧友，WhatsApp/Instagram 较多用于香港同学（`platform_transition_analysis.csv`、`survey_item_statistics.csv`）。边际人数本身不能证明同一个体的保留或替代。Q6.2 缺少微博列，不能比较。两份访谈都没有足够的平台—受众—功能事件，故平台过程属于访谈沉默。

**既有证据。** 文献库没有严格目标人口的 A 级数字研究。DP003（B）只有零散平台片段，最多支持并存和选择性采用可能发生。香港高校生、成人或其他移民社会的 polymedia/media-repertoire 研究（D2-003、D2-006、TM012、TM013，C）只提供媒体组合机制，不能证明中学生平台效果。

**关系。** 当前问卷在严格筛选样本中**支持并扩展**“多个平台并存且按关系分工”的描述，但没有概率抽样、访谈事件或因果识别，不能声称新平台替代旧平台、某平台促进归属，亦不能由平台选择推断文化或政治身份。

## 6. 当前研究相对文献的增量与限制

当前研究的主要增量不是总体估计，而是：

1. 使用严格资格筛选把 24 份完整问卷与两个合资格访谈案例放入同一证据链；
2. 将初期制度/同伴困难与后期回答保持为不同题项，而非伪纵向变化分；
3. 显示相似问卷响应可由不同过程解释，并保留可信任—交心、规则掌握—能力自评等分歧；
4. 为同背景安全圈的时序权衡、同伴代沟通和离港后关系重组提出个案级过程线索；
5. 对文化中介和平台主题明确保留访谈沉默。

限制包括非概率小样本、回顾性自报、只有两个合资格链接案例、访谈选择理由未记录、一份整理式记录、一份未核音且存在工具情境风险的机器转写，以及文献证据中 A 级材料极少且年代较早。因而，本研究只能说当前数据**支持、扩展、复杂化或不同于**某些既有发现，不能据此评估香港所有目标学生或学校政策效果。
"""


def main() -> None:
    path = ROOT / "outputs/reports/literature_comparison.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(REPORT, encoding="utf-8")
    print("literature comparison generated")


if __name__ == "__main__":
    main()
