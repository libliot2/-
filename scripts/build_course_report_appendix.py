def tex_escape(value: object) -> str:
    """Escape LaTeX-sensitive ASCII while preserving Chinese text."""
    text = "" if pd.isna(value) else str(value)
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def strip_markdown_inline(text: str) -> str:
    text = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", tex_escape(text))
    return text


def questionnaire_to_latex() -> str:
    """Convert the simple questionnaire Markdown to stable LaTeX."""
    lines = QUESTIONNAIRE.read_text(encoding="utf-8").splitlines()
    output = [
        "% Generated by scripts/build_course_report_appendix.py",
        r"\begingroup",
        r"\small",
        r"\setlength{\parskip}{0.38em}",
    ]
    in_items = False

    def close_items() -> None:
        nonlocal in_items
        if in_items:
            output.append(r"\end{itemize}")
            in_items = False

    for raw in lines:
        line = raw.strip()
        if not line:
            close_items()
            output.append("")
            continue
        if line.startswith("# "):
            # The document-level title is supplied by Appendix A.
            continue
        if line.startswith("## "):
            close_items()
            output.append(r"\subsection{" + strip_markdown_inline(line[3:]) + "}")
            continue
        if line.startswith("### "):
            close_items()
            output.append(r"\subsubsection{" + strip_markdown_inline(line[4:]) + "}")
            continue
        if line.startswith("#### "):
            close_items()
            output.append(r"\paragraph{" + strip_markdown_inline(line[5:]) + "}")
            continue
        if line.startswith("- "):
            if not in_items:
                output.append(r"\begin{itemize}")
                in_items = True
            output.append(r"\item " + strip_markdown_inline(line[2:]))
            continue
        close_items()
        output.append(strip_markdown_inline(line) + r"\par")

    close_items()
    output.extend([r"\endgroup", ""])
    return "\n".join(output).rstrip() + "\n"


def clean_item_text(text: object) -> str:
    raw = "" if pd.isna(text) else str(text)
    if "—" in raw:
        raw = raw.rsplit("—", 1)[-1]
    match = re.search(r"\(([A-Z])\.\s*(.+)\)$", raw)
    if match:
        raw = match.group(2)
    else:
        raw = re.sub(r"^Q[3456]\([A-Z]\.\s*", "", raw)
        raw = raw.rstrip(")")
    return tex_escape(raw.strip())


def display_question_id(value: object) -> str:
    """Render sub-item IDs as Q5.1(1), avoiding code-like underscores."""
    raw = "" if pd.isna(value) else str(value)
    match = re.fullmatch(r"(Q\d+(?:\.\d+)?)_(\d+)", raw)
    if match:
        raw = f"{match.group(1)}({match.group(2)})"
    return tex_escape(raw)


def public_n_over_n(n: int, valid_n: int, *, include_percentage: bool = True) -> str:
    """Format an aggregate count with primary small-cell suppression."""
    if n in {1, 2}:
        return rf"$<3$/{valid_n}"
    if include_percentage:
        pct = 100 * n / valid_n if valid_n else 0
        return f"{n}/{valid_n} ({pct:.1f}\\%)"
    return f"{n}/{valid_n}"


def ordinal_summary(group: pd.DataFrame) -> str:
    valid_n = int(group["valid_n"].iloc[0])
    numeric = pd.to_numeric(group["response_or_statistic"], errors="coerce")
    positive_n = int(group.loc[numeric.isin([4, 5]), "n"].sum())
    median = float(group["median"].iloc[0])
    q1 = float(group["q1"].iloc[0])
    q3 = float(group["q3"].iloc[0])
    result = (
        f"4--5: {public_n_over_n(positive_n, valid_n)}; "
        f"median {median:.1f} [IQR {q1:.1f}--{q3:.1f}]"
    )
    return result


def multiple_choice_summary(group: pd.DataFrame) -> tuple[str, str]:
    valid_n = int(group["valid_n"].iloc[0])
    selected = group[group["response_or_statistic"].astype(str) == "选择"]
    selected_n = int(selected["n"].iloc[0]) if not selected.empty else 0
    return f"selected: {public_n_over_n(selected_n, valid_n)}", ""


def support_summary(group: pd.DataFrame) -> str:
    valid_n = int(group["valid_n"].iloc[0])
    states = {
        "已获得，而且帮助较大": "major help",
        "已获得，但帮助有限": "limited help",
        "没有获得，但希望获得": "wanted, not received",
        "没有获得，也不需要": "not needed",
    }
    counts: list[int] = []
    labels: list[str] = []
    for source_label, display_label in states.items():
        row = group[group["response_or_statistic"].astype(str) == source_label]
        n = int(row["n"].iloc[0]) if not row.empty else 0
        labels.append(display_label)
        counts.append(n)

    primary = {i for i, n in enumerate(counts) if n in {1, 2}}
    secondary: set[int] = set()
    if len(primary) == 1:
        candidates = [
            (n, i)
            for i, n in enumerate(counts)
            if i not in primary and n > 0
        ]
        if candidates:
            secondary.add(min(candidates)[1])

    values = []
    for index, (display_label, n) in enumerate(zip(labels, counts, strict=True)):
        if index in primary:
            displayed = rf"$<3$/{valid_n}"
        elif index in secondary:
            displayed = "S"
        else:
            displayed = f"{n}/{valid_n}"
        values.append(f"{display_label} {displayed}")
    return "; ".join(values)


def grouped_single_choice_rows(
    variable_name: str, group: pd.DataFrame
) -> list[tuple[str, int]]:
    """Return public-safe grouped categories for single-choice items."""
    source = {
        str(row["response_or_statistic"]): int(row["n"])
        for _, row in group.iterrows()
    }
    if variable_name == "q4_2_overall_fit":
        fixed = [
            ("内地和香港分别在不同方面更适合自己", source.get("内地和香港分别在不同方面更适合自己", 0)),
            ("两边都能够适应", source.get("两边都能够适应", 0)),
            ("香港的学习和生活环境整体上更适合自己", source.get("香港的学习和生活环境整体上更适合自己", 0)),
        ]
        used = sum(n for _, n in fixed)
        return fixed + [("其他总体适合感描述", int(group["valid_n"].iloc[0]) - used)]
    if variable_name == "q6_3_old_friend_platform":
        wechat = source.get("微信", 0)
        return [("微信", wechat), ("其他平台", int(group["valid_n"].iloc[0]) - wechat)]
    if variable_name == "q6_4_hk_peer_platform":
        whatsapp = source.get("WhatsApp", 0)
        wechat = source.get("微信", 0)
        total = int(group["valid_n"].iloc[0])
        return [
            ("WhatsApp", whatsapp),
            ("微信", wechat),
            ("其他平台", total - whatsapp - wechat),
        ]
    if variable_name == "q7_1_peer_network":
        kept_labels = [
            "同时维持几个不同背景的朋友圈",
            "根据课程、兴趣和场景进入不同群体",
            "主要与内地背景同学交往",
        ]
        fixed = [(label, source.get(label, 0)) for label in kept_labels]
        used = sum(n for _, n in fixed)
        return fixed + [("其他同伴网络描述", int(group["valid_n"].iloc[0]) - used)]
    return [(str(row["response_or_statistic"]), int(row["n"])) for _, row in group.iterrows()]


def result_rows_for_role(df: pd.DataFrame, role: str) -> list[tuple[str, str, str]]:
    subset = df[df["analysis_role"] == role]
    rows: list[tuple[str, str, str]] = []
    for variable_name, group in subset.groupby("variable_name", sort=False):
        statistic_type = str(group["statistic_type"].iloc[0])
        question_id = display_question_id(group["question_id"].iloc[0])
        item = clean_item_text(group["item_text"].iloc[0])

        if statistic_type == "ordinal_distribution":
            result = ordinal_summary(group)
            rows.append((question_id, item, result))
        elif statistic_type == "multiple_choice":
            if variable_name in {"q6_2_later_wechat", "q6_2_later_instagram"}:
                result = "selected: S (cross-table suppression)"
            else:
                result, _ = multiple_choice_summary(group)
            rows.append((question_id, item, result))
        elif statistic_type == "support_status_distribution":
            result = support_summary(group)
            rows.append((question_id, item, result))
        elif statistic_type == "single_choice":
            valid_n = int(group["valid_n"].iloc[0])
            first = True
            for category_raw, n in grouped_single_choice_rows(variable_name, group):
                category = tex_escape(category_raw)
                rows.append(
                    (
                        question_id if first else "",
                        category,
                        public_n_over_n(n, valid_n),
                    )
                )
                first = False
        else:
            raise ValueError(f"Unsupported statistic_type for {variable_name}: {statistic_type}")
    return rows


def longtable(title: str, label: str, role_rows: list[tuple[str, list[tuple[str, str, str]]]]) -> str:
    lines = [
        r"\begingroup",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{3.5pt}",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{1.35cm}>{\raggedright\arraybackslash}p{7.15cm}>{\raggedright\arraybackslash}p{5.55cm}@{}}",
        rf"\caption{{{tex_escape(title)}}}\label{{{label}}}\\",
        r"\toprule",
        r"Question & Item or response category & Aggregated result \\",
        r"\midrule",
        r"\endfirsthead",
        rf"\multicolumn{{3}}{{l}}{{\footnotesize\itshape {tex_escape(title)} (continued)}}\\",
        r"\toprule",
        r"Question & Item or response category & Aggregated result \\",
        r"\midrule",
        r"\endhead",
        r"\midrule",
        r"\multicolumn{3}{r}{\footnotesize Continued on next page}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    for role, rows in role_rows:
        lines.append(
            r"\rowcolor{ReportLightBlue}\multicolumn{3}{@{}l}{\bfseries "
            + tex_escape(ROLE_LABELS[role])
            + r"}\\"
        )
        for question_id, item, result in rows:
            lines.append(f"{question_id} & {item} & {result} \\\\")
    lines.extend([r"\end{longtable}", r"\endgroup", ""])
    return "\n".join(lines)


def sample_profile_table() -> str:
    df = pd.read_csv(SAMPLE_PROFILE, encoding="utf-8-sig")
    lines = [
        r"\begingroup",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{4.2cm}>{\raggedright\arraybackslash}p{6.3cm}rr@{}}",
        r"\caption{Grouped characteristics of the observed sample}\label{tab:appendix-sample-profile}\\",
        r"\toprule",
        r"Dimension & Category & $n/N$ & \% \\",
        r"\midrule",
        r"\endfirsthead",
        r"\multicolumn{4}{l}{\footnotesize\itshape Grouped sample characteristics (continued)}\\",
        r"\toprule",
        r"Dimension & Category & $n/N$ & \% \\",
        r"\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    previous = None
    for _, row in df.iterrows():
        dimension = tex_escape(row["dimension"]) if row["dimension"] != previous else ""
        previous = row["dimension"]
        category = tex_escape(row["category"])
        n = int(row["n"])
        denominator = int(row["denominator"])
        percentage = float(row["percentage"])
        lines.append(f"{dimension} & {category} & {n}/{denominator} & {percentage:.1f} \\\\")
    lines.extend(
        [
            r"\end{longtable}",
            r"\begin{boundarybox}",
            r"Categories are grouped so that no displayed cell contains fewer than three participants. Teaching-language categories are multiple response and therefore do not sum to 100\%.",
            r"\end{boundarybox}",
            r"\endgroup",
            "",
        ]
    )
    return "\n".join(lines)


def platform_transition_table() -> str:
    """Build a compact, public-safe table for transitions cited in the report."""
    df = pd.read_csv(EXPLORATORY_EXTENSION, encoding="utf-8-sig")
    platforms = [
        ("WeChat", "wechat"),
        ("WhatsApp", "whatsapp"),
        ("Instagram", "instagram"),
    ]
    states = ["retained", "adopted", "stopped", "neither"]
    lines = [
        r"\begin{table}[H]",
        r"  \caption{Selected within-platform paired transitions across recalled periods}",
        r"  \label{tab:appendix-platform-transitions}",
        r"  \centering",
        r"  \footnotesize",
        r"  \setlength{\tabcolsep}{7pt}",
        r"  \begin{tabular}{@{}lrrrr@{}}",
        r"    \toprule",
        r"    Platform & Retained & Adopted later & Stopped later & Neither period \\",
        r"    \midrule",
    ]
    for label, slug in platforms:
        values = []
        for state in states:
            finding_id = f"PLATFORM_{slug}_{state}"
            row = df[df["finding_id"] == finding_id]
            if len(row) != 1:
                raise ValueError(f"Expected one transition row: {finding_id}")
            raw = str(row.iloc[0]["numerator"]).strip()
            values.append("S" if raw == "<3" else f"{int(float(raw))}/35")
        if slug == "instagram":
            # Complementary cross-table suppression: publishing "neither=12"
            # together with adopted=22 would recover pre-period use as 1.
            values[states.index("neither")] = "S"
        lines.append(
            f"    {tex_escape(label)} & " + " & ".join(values) + r" \\"
        )
    lines.extend(
        [
            r"    \bottomrule",
            r"  \end{tabular}",
            r"  \vspace{0.35em}",
            "",
            r"  \begin{minipage}{\textwidth}",
            r"    \footnotesize\textit{Note.} Each row classifies the same 35 respondents within one platform. S suppresses a cell smaller than three and, where necessary, its complementary small cell. Transitions describe paired retrospective selections rather than observed behavioural change, belonging or identity. The later-period Weibo export column was absent and was not reconstructed.",
            r"  \end{minipage}",
            r"\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def survey_results_to_latex() -> str:
    df = pd.read_csv(SURVEY_STATS, encoding="utf-8-sig")
    parts = [
        "% Generated by scripts/build_course_report_appendix.py",
        sample_profile_table(),
        r"\begin{boundarybox}",
        (
            r"For ordinal items, ``4--5'' reports the count selecting either of the "
            r"two upper response categories; its substantive meaning depends on the "
            r"question wording. Multiple-response rows report endorsements rather "
            r"than rankings. Special responses are excluded from the valid denominator "
            r"and remain separately identified where present in the export. These are "
            r"aggregated sample summaries, "
            r"not participant-level records. Counts of one or two are displayed as "
            r"$<3$. S denotes a direct or complementary privacy suppression, including "
            r"cross-table suppression where related published summaries would otherwise "
            r"allow recovery of a small transition cell."
        ),
        r"\end{boundarybox}",
        "",
    ]
    for index, (title, roles) in enumerate(DOMAIN_ROLES, start=1):
        parts.append(r"\needspace{15\baselineskip}")
        parts.append(r"\subsection{" + tex_escape(title) + "}")
        role_rows = [(role, result_rows_for_role(df, role)) for role in roles]
        parts.append(
            longtable(
                title=f"Public-safe aggregate summaries: {title.lower()}",
                label=f"tab:appendix-survey-domain-{index}",
                role_rows=role_rows,
            )
        )
        if "platform_later" in roles:
            parts.append(platform_transition_table())
    return "\n".join(parts).rstrip() + "\n"


