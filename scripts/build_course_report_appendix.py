def main() -> None:
    OVERLEAF_SRC.mkdir(parents=True, exist_ok=True)
    outputs = {
        "appendix_questionnaire.tex": questionnaire_to_latex(),
        "appendix_survey_results.tex": survey_results_to_latex(),
        "appendix_open_text.tex": open_text_to_latex(),
    }
    for filename, content in outputs.items():
        path = OVERLEAF_SRC / filename
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
